#!/usr/bin/env python3
"""Assemble the unpacked extension from the same sources the web build uses."""
import json, os, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXT  = os.path.join(ROOT, "extension")

# agent.js is copied, never forked. The extension and the web build and the eval
# harness all run the same file; if they diverge, the demo stops proving anything.
shutil.copyfile(os.path.join(ROOT, "src", "agent.js"), os.path.join(EXT, "agent.js"))

cat = json.load(open(os.path.join(ROOT, "data", "catalog.json"), encoding="utf-8"))
profiles = json.load(open(os.path.join(ROOT, "data", "profiles.json"), encoding="utf-8"))["profiles"]
cached = json.load(open(os.path.join(ROOT, "data", "cached_runs.json"), encoding="utf-8"))
cached.pop("_note", None)

quiz = json.load(open(os.path.join(ROOT, "data", "quiz.json"), encoding="utf-8"))
quiz.pop("note", None)

def attach_posters(catalog):
    """Data URIs win when we have them (a published artifact's CSP blocks remote
    images); otherwise the TMDB url, which works in the extension and in a local
    file, and falls back to a generated tone card if the host page refuses it."""
    hit = 0
    for name, key in (("posters.json", "data"), ("poster_urls.json", "url")):
        p = os.path.join(ROOT, "data", name)
        if not os.path.exists(p):
            continue
        table = json.load(open(p, encoding="utf-8"))
        for item in catalog:
            if item.get("poster_url"):
                continue
            if item["id"] in table:
                item["poster_url"] = table[item["id"]]; hit += 1
        if hit:
            break
    return hit

_posters = attach_posters(cat)
print(f"  posters attached: {_posters}")


with open(os.path.join(EXT, "data.js"), "w", encoding="utf-8") as f:
    f.write("/* generated by build/build_extension.py — do not edit */\n")
    f.write("const CATALOG = "     + json.dumps(cat,      ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("const PROFILES = "    + json.dumps(profiles, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("const CACHED_RUNS = " + json.dumps(cached,   ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("const QUIZ = "         + json.dumps(quiz,     ensure_ascii=False, separators=(",", ":")) + ";\n")

# icons: a lit marquee dot on the app's ground colour
try:
    from PIL import Image, ImageDraw
    for size in (48, 128):
        img = Image.new("RGBA", (size, size), (12, 16, 23, 255))
        d = ImageDraw.Draw(img)
        r = size * 0.19
        c = size / 2
        d.ellipse([c - r, c - r, c + r, c + r], fill=(255, 122, 61, 255))
        pad = size * 0.16
        d.rounded_rectangle([pad, pad, size - pad, size - pad], radius=size * 0.14,
                            outline=(255, 122, 61, 120), width=max(1, size // 32))
        img.save(os.path.join(EXT, "icons", f"icon{size}.png"))
    icons = "written"
except Exception as e:
    icons = f"skipped ({e})"

size = sum(os.path.getsize(os.path.join(EXT, f)) for f in os.listdir(EXT) if os.path.isfile(os.path.join(EXT, f)))
print(f"extension built — {size/1024:.0f} KB · icons: {icons}")
