def slug(t):
    return re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")

def build():
    out = []
    seen = set()
    for (title, kind, year, runtime, seasons, genres, cert, brand,
         energy, warmth, tags, overview) in ROWS:
        tid = slug(title)
        assert tid not in seen, f"duplicate id {tid}"
        seen.add(tid)
        out.append({
            "id": tid,
            "title": title,
            "kind": kind,
            "year": year,
            "runtime": runtime,          # movies: total; series: average episode
            "seasons": seasons,
            "genres": genres,
            "certification": cert,
            "brand": brand,
            "energy": energy,
            "warmth": warmth,
            "tone_tags": tags,
            "overview": overview,
            "poster_url": None,          # filled by fetch_posters_local.mjs
            "tmdb_id": None,
            "kid_safe": None,            # set by enrich_audience.py — NOT the certification
        })
    return out

